"""Finite-orbit paired experiment; exact projection identity, no LLM claim."""
import os
os.environ['OPENBLAS_NUM_THREADS']='1'
import itertools,json
from pathlib import Path
import numpy as np
from symmetry import unitary, permutation_indices
root=Path(__file__).resolve().parent
n=3; d=2**n
perms=list(itertools.permutations(range(n)))
indices=[permutation_indices(p) for p in perms]
# All real product inputs from three distinct Bloch angles: complete S3 orbits.
xs=list(itertools.product([.2,.9,1.7],repeat=n))
states=[]
for x in xs:
    state=np.array([1.])
    for angle in x: state=np.kron(state,[np.cos(angle/2),np.sin(angle/2)])
    states.append(state)
states=np.array(states)
zmean=np.array([np.mean([1-2*((i>>(n-1-j))&1) for j in range(n)]) for i in range(d)])
def output(u): return (abs(states@u.T)**2)@zmean
# Symmetric target generated by nonconstant collective rotation.
rot=[{'gate':'RY','wire':i,'param':'a'} for i in range(n)]
yinv=output(unitary(rot,{'a':.4},n))
# A centered noninvariant target component orthogonal to all invariant functions.
yraw=np.array([np.cos(x[0]) for x in xs]); lookup={x:i for i,x in enumerate(xs)}
orbits=np.array([[lookup[tuple(x[j] for j in p)] for p in perms] for x in xs])
yasym=yraw-yraw[orbits].mean(axis=1)
rows=[]
for seed in range(8):
    rng=np.random.default_rng(seed)
    a,b=rng.uniform(-1,1,2)
    for eps in [0.,.1,.3,.6,1.]:
        # One-direction CRZ generator interpolated to its exact group twirl.
        # Each unordered pair has forward angle b*(1+eps)/2 and reverse b*(1-eps)/2.
        gates=rot.copy()
        for i in range(n):
            for j in range(i+1,n):
                gates += [{'gate':'CRZ','wires':[i,j],'param':'forward'}, {'gate':'CRZ','wires':[j,i],'param':'reverse'}]
        gates += [{'gate':'RY','wire':i,'param':'read'} for i in range(n)]
        f=output(unitary(gates,{'a':a,'forward':b*(1+eps)/2,'reverse':b*(1-eps)/2,'read':.7},n))
        fbar=f[orbits].mean(axis=1)
        defect=float(np.mean((f-fbar)**2))
        for eta in [0.,.25,.5,1.]:
            y=yinv+eta*yasym
            risk=float(np.mean((f-y)**2)); averaged=float(np.mean((fbar-y)**2))
            cross=float(np.mean((f-fbar)*yasym))
            assert np.isclose(risk-averaged,defect-2*eta*cross,atol=1e-12)
            if eta==0: assert np.isclose(risk-averaged,defect,atol=1e-12)
            rows.append(dict(seed=seed,epsilon=eps,eta=eta,risk=risk,averaged_risk=averaged,output_defect=defect,cross=cross,output_variance=float(np.var(f))))
# Negative control: target equal to an asymmetric model prediction.
# For this target, averaging strictly increases risk by its removed variance.
neg={'raw_risk':0.,'averaged_risk':float(np.mean((fbar-f)**2)),'output_defect':defect}
assert neg['averaged_risk']>1e-8
out={'description':'8 paired circuit parameter seeds; 27 product states closed under S3; no training; exact full orbit averaging','rows':rows,'negative_control_target_is_asymmetric_prediction':neg}
(root/'risk_pilot.json').write_text(json.dumps(out,indent=2))
try:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig,axs=plt.subplots(1,2,figsize=(9,3.5))
    for seed in range(8):
        selected=[r for r in rows if r['seed']==seed and r['eta']==0]
        axs[0].plot([r['epsilon'] for r in selected],[r['output_defect'] for r in selected],alpha=.55)
    axs[0].set(xlabel='Symmetry-breaking strength epsilon',ylabel='Output orbit variance')
    base=[r for r in rows if r['eta']==0]
    axs[1].scatter([r['output_defect'] for r in base],[r['risk']-r['averaged_risk'] for r in base],s=12)
    mx=max(r['output_defect'] for r in base); axs[1].plot([0,mx],[0,mx],'k--',lw=1)
    axs[1].set(xlabel='Output orbit variance',ylabel='Risk removed by output averaging')
    fig.tight_layout();fig.savefig(root/'risk_pilot.png',dpi=180);plt.close(fig)
except ImportError: pass
print(json.dumps({'rows':len(rows),'negative_control':neg,'max_defect':max(r['output_defect'] for r in rows)}))
