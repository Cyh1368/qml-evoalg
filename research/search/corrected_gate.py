# --- frozen tolerance (Addendum A6.1; do not tune after seeing results) ----------
ATOL_ABS = 1e-12
ATOL_REL = 1e-9
TOL_SWEEP = [0.0, 1e-15, 1e-12, 1e-9, 1e-6, 1e-3]
GATE_ROWS = 64            # harness LABEL_ROWS, so gate cost is comparable
PROBE_ROWS = 256
PROBE_SEED = 777          # same probe seed as A5.2 (never read by the gate)
MC_DRAWS = 400            # per proposal distribution
MC_SEED = 60606
N_TRANSPOSITIONS = 15
N_RANDOM = 20
PANEL_SEED = 4242


# --------------------------------------------------------------------- primitives
def sha_sorted(elems):
    """Stable identity for a subgroup: digest of its sorted element list."""
    h = hashlib.sha256()
    for e in sorted(tuple(x) for x in elems):
        h.update(repr(e).encode())
    return h.hexdigest()[:12]


CLOSURE_CAP = 2000      # never enumerate a huge group: n = 9 has |S_9| = 362880


class ClosureTooLarge(Exception):
    """Raised when a closure exceeds CLOSURE_CAP."""


def closure(gens, n, cap=None):
    """Group generated by ``gens`` (lists of site images), as a sorted list of tuples.

    Raises ``ClosureTooLarge`` past ``cap`` elements (default ``CLOSURE_CAP``). Without a
    cap, a panel entry that generates the full symmetric group at ``n = 9`` asks for
    362880 elements and then 362880 oracle calls per gate test, which is not a computation
    anyone should start. The cap also carries an epistemic note recorded at the call sites:
    sampling group elements can *refute* a symmetry (one violating element suffices) but can
    never certify one.
    """
    cap = CLOSURE_CAP if cap is None else int(cap)
    seen = {tuple(range(n))}
    frontier = [tuple(range(n))]
    gs = [tuple(g) for g in gens]
    while frontier:
        new = []
        for a in frontier:
            for g in gs:
                for x in (a, g):
                    c = tuple(a[i] for i in g) if x is g else tuple(g[i] for i in a)
                    if c not in seen:
                        seen.add(c)
                        new.append(c)
            if len(seen) > cap:
                raise ClosureTooLarge("%d+ elements (cap %d)" % (len(seen), cap))
        frontier = new
    return sorted(seen)


def closure_size(gens, n, cap=None):
    """Closure order, or ``None`` when the closure exceeds the cap."""
    try:
        return len(closure(gens, n, cap=cap))
    except ClosureTooLarge:
        return None


def transform(task, rows, perm):
    """Relabel ``rows`` by ``perm``, using the family's own action.

    Delegates to ``verify_semantics.action_columns``: for ``graphs_n6`` the input carries
    one bit per **edge** (15 columns for 6 vertices), so a vertex permutation induces a
    permutation of columns and a naive ``rows[:, perm]`` silently produces a 6-column
    array that the oracle then rejects. That mistake made an earlier version of this
    module crash on graphs.
    """
    from research.search.verify_semantics import action_columns
    return action_columns(task, rows, perm)


def label_test(task, gens, target, rows, atol_abs=ATOL_ABS, atol_rel=ATOL_REL,
               all_columns=False):
    """Label-preservation test. ``all_columns=True`` reproduces the implemented gate.

    Returns the violated fraction over (element, row) entries, the maximum discrepancy,
    and the wall time. A violation is ``|y(gx) - y(x)| > atol_abs + atol_rel * |y(x)|``;
    with ``atol_abs = atol_rel = 0`` this is the implemented exact-equality test.
    """
    t0 = time.time()
    rows = np.asarray(rows)
    y0 = _labels(task, rows, target, all_columns)
    viol = tot = 0
    worst = 0.0
    try:
        elems = closure(gens, int(task.n_qubits))
        truncated = False
    except ClosureTooLarge:
        # sample instead: a violation found is conclusive, an absence of violation is not
        rng = np.random.default_rng(1234)
        elems = [tuple(rng.permutation(int(task.n_qubits)))
                 for _ in range(min(GATE_ROWS, CLOSURE_CAP))]
        truncated = True
    for g in elems:
        yt = _labels(task, transform(task, rows, g), target, all_columns)
        d = np.abs(yt - y0)
        tol = atol_abs + atol_rel * np.abs(y0)
        viol += int((d > tol).sum())
        tot += int(d.size)
        worst = max(worst, float(d.max()))
    return {"violated_fraction": viol / max(tot, 1), "n_violations": viol,
            "n_entries": tot, "max_discrepancy": worst,
            "closure_order": closure_size(gens, int(task.n_qubits)),
            "closure_elements_tested": len(elems),
            "closure_truncated_sampled": truncated,
            "certifies_soundness": (not truncated),
            "seconds": time.time() - t0}


def _labels(task, rows, target, all_columns):
    y = np.asarray(task.label_oracle(rows, target=None if all_columns else target),
                   dtype=float)
    return y if y.ndim == 2 else y.reshape(-1, 1)


def sound_on_probe(task, gens, target, probe, atol_abs=ATOL_ABS, atol_rel=ATOL_REL):
    """Truth determination: does every *generator* preserve ``target`` on the probe?

    Generators suffice (a group is a symmetry iff its generators are), which is what makes
    the diagnostic affordable at n = 9.
    """
    rows = np.asarray(task.x)[probe]
    y0 = _labels(task, rows, target, False)
    worst = 0.0
    for g in [tuple(x) for x in gens]:
        d = np.abs(_labels(task, transform(task, rows, g), target, False) - y0)
        worst = max(worst, float(d.max()))
    return worst <= atol_abs + atol_rel * float(np.abs(y0).max()), worst


# --------------------------------------------------------------------- A6.6 panel
def panel(n, seed=PANEL_SEED):
    """The canonical A5.3 panel, imported, never re-implemented.

    An earlier revision of this module carried its own copy of the nine generator sets and
    its docstring claimed they were the A5.3 panel. They were not: the reflection was
    ``-1-i`` instead of ``-i``, ``rotation_subgroup_c2`` was ``rho**4`` (order 3, the same
    subgroup as ``rotation_subgroup_c3``) instead of ``rho**3`` (order 2), and
    ``full_symmetric`` used different generators. The drift changed the reported number of
    distinct subgroups, which is exactly the quantity A6.6 is about, so the copy is deleted
    and the canonical panel is imported. ``test_corrected_gate`` pins the two to be the same
    mapping so they cannot drift again.
    """
    from research.search.verify_semantics import panel as canonical
    return canonical(n, seed=seed)


def panel_reanalysis(task, targets, probe):
    """Nine entries -> unique subgroups, with truth and each gate's decision.

    Descriptive coverage only. The previous report attached Wilson intervals to counts over
    entries that generate the *same* subgroup; that is retracted here.
    """
    n = int(task.n_qubits)
    rows = np.asarray(task.x)[:GATE_ROWS]
    out = []
    for name, gens in panel(n).items():
        try:
            H = closure(gens, n)
            order, sha = len(H), sha_sorted(H)
        except ClosureTooLarge:
            H, order, sha = None, None, ">cap"
        row = {"entry": name, "n_generators": len(gens), "closure_order": order,
               "closure_sha": sha}
        for tgt in targets:
            truth, worst = sound_on_probe(task, gens, tgt, probe)
            imp = label_test(task, gens, tgt, rows, 0.0, 0.0, all_columns=True)
            cor = label_test(task, gens, tgt, rows, ATOL_ABS, ATOL_REL, all_columns=False)
            row[tgt] = {"sound": bool(truth), "probe_worst": worst,
                        "implemented_accepts": imp["violated_fraction"] == 0.0,
                        "corrected_accepts": cor["violated_fraction"] == 0.0,
                        "implemented_violated": imp["violated_fraction"],
                        "corrected_violated": cor["violated_fraction"],
                        "tolerance_sweep": {
                            ("%.0e" % t if t else "0"):
                                label_test(task, gens, tgt, rows, t, 0.0,
                                           all_columns=False)["violated_fraction"] == 0.0
                            for t in TOL_SWEEP}}
        out.append(row)
    uniq = {}
    for r in out:
        uniq.setdefault(str(r["closure_sha"]), []).append(r["entry"])
    return {"entries": out, "unique_subgroups": {k: v for k, v in uniq.items()},
            "n_entries": len(out), "n_unique_subgroups": len(uniq)}


# ------------------------------------------------------- A6.5 distribution-aware
def _sample_Q(kind, n, rng, empirical=None, k=1):
    if kind == "uniform_single":
        return [tuple(rng.permutation(n))]
    if kind == "uniform_k":
        return [tuple(rng.permutation(n)) for _ in range(k)]
    if kind == "empirical_llm":
        return list(empirical[int(rng.integers(len(empirical)))])
    raise ValueError(kind)


def accept_probability(task, target, kind, probe, draws=MC_DRAWS, seed=MC_SEED,
                       empirical=None, k=1):
    """Pr_{H ~ Q}[H is a label symmetry of target], by probe-testing each draw.

    The Wilson interval here *is* defensible: the draws are independent by construction,
    which is exactly what the fixed panel was not.
    """
    rng = np.random.default_rng(seed)
    t0 = time.time()
    hits = np.zeros(draws, bool)
    orders = np.zeros(draws, int)
    for i in range(draws):
        gens = _sample_Q(kind, int(task.n_qubits), rng, empirical, k)
        hits[i], _ = sound_on_probe(task, gens, target, probe)
        sz = closure_size(gens, int(task.n_qubits))
        orders[i] = sz if sz is not None else CLOSURE_CAP
    el = _P.wilson_ci(int(hits.sum()), int(draws))
    return {"Q": kind, "k": k, "draws": int(draws), "accepted": int(hits.sum()),
            "accept_rate": float(hits.mean()), "ci95_low": el["ci95_low"],
            "ci95_high": el["ci95_high"],
            "median_closure_order": float(np.median(orders)),
            "seconds": time.time() - t0}


def exact_L(task, target, probe):
    """Enumerate the label-symmetry group when n! is affordable (n <= 6)."""
    n = int(task.n_qubits)
    if math.factorial(n) > 5040:
        return None
    rows = np.asarray(task.x)[probe]
    y0 = _labels(task, rows, target, False)
    elems = []
    t0 = time.time()
    for perm in itertools.permutations(range(n)):
        d = np.abs(_labels(task, transform(task, rows, perm), target, False) - y0)
        if bool((d <= ATOL_ABS + ATOL_REL * np.abs(y0)).all()):
            elems.append(tuple(perm))
    return {"order": len(elems), "of_symmetric_group": math.factorial(n),
            "ratio": len(elems) / math.factorial(n), "seconds": time.time() - t0,
            "elements": elems}


def square_symmetries():
    """The eight symmetries of the 3x3 board (dihedral group D4), sites row-major."""
    def idx(r, c):
        return 3 * r + c
    rot = [idx(2 - c, r) for r in range(3) for c in range(3)]      # 90 degrees
    ref = [idx(r, 2 - c) for r in range(3) for c in range(3)]      # horizontal flip
    return closure([rot, ref], 9)


# ------------------------------------------------------------------ A6.4 noise
def noise_sweep(task, target, eps_grid, gens_valid, gens_invalid, probe, gate_rows,
                seed=20261207):
    """Defective vs corrected gate as the target's symmetry becomes approximate."""
    rng = np.random.default_rng(seed)
    x = np.asarray(task.x)
    base = _labels(task, x[gate_rows], target, False).reshape(-1)
    # perturbation eps * (x . v) for a fixed random v, which is NOT invariant under the
    # site-permutation action. An integer row hash or a Hamming weight would be wrong
    # here: these inputs are continuous vectors, and any weight-based index makes the
    # perturbation itself symmetric, so the "approximate symmetry" regime would test
    # nothing (this mistake made an earlier version of this sweep report every noisy
    # target as exactly symmetric).
    v = rng.standard_normal(int(task.n_qubits))
    rows = {"eps": [], "defective_accepts_valid": [], "corrected_accepts_valid": [],
            "defective_accepts_invalid": [], "corrected_accepts_invalid": [],
            "probe_worst_valid": [], "label_shift_max": []}
    for eps in eps_grid:
        def oracle(r, _eps=eps):
            r = np.asarray(r, dtype=float)
            y = _labels(task, r, target, False).reshape(-1)
            return y + _eps * (r @ v)
        class _T:
            pass
        t2 = _T()
        t2.n_qubits = task.n_qubits
        t2.x = task.x
        t2.label_oracle = lambda r, target=None, _o=oracle: _o(r)
        dv = label_test(t2, gens_valid, target, x[gate_rows], 0.0, 0.0, all_columns=False)
        cv = label_test(t2, gens_valid, target, x[gate_rows], ATOL_ABS, ATOL_REL)
        di = label_test(t2, gens_invalid, target, x[gate_rows], 0.0, 0.0, all_columns=False)
        ci = label_test(t2, gens_invalid, target, x[gate_rows], ATOL_ABS, ATOL_REL)
        truth_v, worst_v = sound_on_probe(t2, gens_valid, target, probe)
        rows["eps"].append(eps)
        rows["defective_accepts_valid"].append(dv["violated_fraction"] == 0.0)
        rows["corrected_accepts_valid"].append(cv["violated_fraction"] == 0.0)
        rows["defective_accepts_invalid"].append(di["violated_fraction"] == 0.0)
        rows["corrected_accepts_invalid"].append(ci["violated_fraction"] == 0.0)
        rows["probe_worst_valid"].append(worst_v)
        rows["label_shift_max"].append(float(np.abs(eps * (x @ v)).max()))
    return rows


# --------------------------------------------------------------------- utilities
def _empirical_hypotheses(run_dir):
    import glob
    out = []
    for p in sorted(glob.glob(os.path.join(run_dir, "run_*.json"))):
        with open(p) as fh:
            log = json.load(fh)
        for prop in log.get("proposals", []):
            hyp = (prop.get("candidate") or {}).get("hypothesis") or {}
            g = hyp.get("generators")
            if g:
                out.append([[int(i) for i in gen] for gen in g])
        best = (log.get("best") or {}).get("candidate") or {}
        g = (best.get("hypothesis") or {}).get("generators")
        if g:
            out.append([[int(i) for i in gen] for gen in g])
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(prog="research/search/corrected_gate.py")
    ap.add_argument("--families", default="ring_n6,graphs_n6,tictactoe_n9")
    ap.add_argument("--runs", default="logs/runs_confirm")
    ap.add_argument("--out", default="research/search/corrected_gate.json")
    a = ap.parse_args(argv)
    emp = _empirical_hypotheses(a.runs)
    out = {"protocol": "A6", "atol_abs": ATOL_ABS, "atol_rel": ATOL_REL,
           "tol_sweep": TOL_SWEEP, "probe_rows": PROBE_ROWS, "probe_seed": PROBE_SEED,
           "gate_rows": GATE_ROWS, "mc_draws": MC_DRAWS, "mc_seed": MC_SEED,
           "n_empirical_hypotheses": len(emp), "families": {}}
    for fam in a.families.split(","):
        task = _tasks.load_family(fam.strip(), development=True, locked=False)
        n = int(task.n_qubits)
        from research.search.verify_semantics import probe_indices
        # probe excludes the rows the gate reads, as in A5.2
        probe = probe_indices(task, n_rows=PROBE_ROWS, seed=PROBE_SEED)
        gate_rows = np.arange(min(GATE_ROWS, len(task.x)))
        targets = list(task.targets.keys())
        entry = {"n_qubits": n, "targets": targets, "primary": task.primary_target,
                 "declared_generators": [list(g) for g in task.generators],
                 "factorial_n": math.factorial(n),
                 "panel": panel_reanalysis(task, targets, probe),
                 "exact_L": {}, "accept": {}}
        for tgt in targets:
            ex = exact_L(task, tgt, probe)
            if ex is not None:
                elems = ex.pop("elements")
                ex["is_group"] = len(closure(elems, n)) == len(elems)
                entry["exact_L"][tgt] = ex
            emp_here = [g for g in emp if all(len(x) == n for x in g)]
            for kind, kw in [("uniform_single", {}), ("uniform_k", {"k": 2}),
                             ("uniform_k", {"k": 3}),
                             ("empirical_llm", {"empirical": emp_here}
                              if emp_here else None)]:
                if kw is None:
                    continue
                r = accept_probability(task, tgt, kind, probe, empirical=emp,
                                       k=kw.get("k", 1))
                # cross-check the MC estimator against the exact ratio where available
                if tgt in entry["exact_L"] and kind == "uniform_single":
                    r["exact_single_perm_ratio"] = entry["exact_L"][tgt]["ratio"]
                entry["accept"].setdefault(tgt, []).append(r)
        # declared group and a mismatched group, for the noise sweep
        declared = [list(g) for g in task.generators]
        mm = None
        rs = np.random.default_rng(31337)
        for _ in range(200):
            p = tuple(rs.permutation(n))
            if not set(closure([list(p)], n)) <= set(closure(declared, n)):
                mm = [list(p)]
                break
        entry["noise_sweep"] = noise_sweep(
            task, task.primary_target,
            [0.0, 1e-12, 1e-9, 1e-6, 1e-3, 1e-2], declared, mm or declared,
            probe, gate_rows) if mm else "no mismatched group found"
        if n == 9:
            sq = square_symmetries()
            entry["board_symmetries"] = {
                "n_enumerated": len(sq),
                "all_sound_on_probe": all(sound_on_probe(task, [g], task.primary_target,
                                                         probe)[0] for g in sq),
                "note": ("algebraic anchor for the 3x3 board: the eight square symmetries, "
                         "tested directly; 9! = 362880 permutations are never enumerated")}
        out["families"][fam.strip()] = entry
        print("%s done" % fam, flush=True)
    with open(a.out, "w") as fh:
        json.dump(out, fh, indent=1, default=str)
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
