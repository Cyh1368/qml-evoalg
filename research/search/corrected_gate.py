"""Corrected label gate, panel re-analysis, and a distribution-aware diagnostic (A6).

Third-round review, verified in source: the deployed label test
``verifier_bridge.label_preservation`` defaults to ``tolerance=0.0`` and calls
``task.label_oracle(rows)`` with no ``target=``, so it demands that a hypothesis preserve
*every* target column at exact floating-point equality. This module supplies the corrected
comparator (A6.1) and the three re-analyses the review asked for.

Contents
--------
A6.1  ``label_test`` / ``corrected gate``: scored target only, tolerance
      ``tol = ATOL_ABS + ATOL_REL * |y|`` with the frozen constants below.
A6.6  ``panel_reanalysis``: the fixed panel as **nine generator-set entries**, deduplicated
      to **unique subgroups**, reported as descriptive coverage. No Wilson interval: a
      hand-chosen panel is not a sampling population.
A6.5  ``accept_probability``: ``Pr_{H ~ Q}[H is a label symmetry of t]`` estimated by Monte
      Carlo under declared proposal distributions Q, with the enumeration cost of the old
      ``|L_t|/|S_n|`` stated next to it, and validated against the exact ``L_t`` where ``n!``
      is still enumerable. ``n = 9`` is sampling-only: 362880 permutations is not.
A6.4  ``noise_sweep``: the approximate-symmetry regime that separates "our gate was buggy"
      from "label gates are a recall bottleneck".

Run as a module on a compute node; see ``research/search/job_corrected_gate.sh``.
"""
