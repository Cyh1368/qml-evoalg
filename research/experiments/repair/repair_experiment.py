ARMS = ("original", "repaired", "control")


# ----------------------------------------------------------------- group tools
def group_closure(generators):
    """Full group generated by ``generators`` (one-line perms) via BFS closure."""
    n = len(generators[0])
    ident = tuple(range(n))

    def compose(p, q):  # (p o q)[i] = p[q[i]]
        return tuple(p[q[i]] for i in range(n))

    elements = {ident}
    frontier = [ident]
    while frontier:
        p = frontier.pop()
        for g in generators:
            for h in (compose(p, tuple(g)), compose(tuple(g), p)):
                if h not in elements:
                    elements.add(h)
                    frontier.append(h)
    return sorted(elements)


def transform_rows(rows, perm):
    """Relabel input sites: ``out[:, i] = rows[:, perm[i]]``."""
    return np.asarray(rows)[:, list(perm)]


# ------------------------------------------------------------------ ansatz arms
def _crz_pairs(n):
    return list(itertools.combinations(range(n), 2))


def arm_block(arm, n):
    """Block gate list for an arm; equal parameter count {a,b,c} across arms."""
    block = [{"gate": "RY", "wire": i, "param": "a"} for i in range(n)]
    for i, j in _crz_pairs(n):
        if arm == "original":
            block.append({"gate": "CRZ", "wires": [i, j], "param": "b"})
        elif arm == "repaired":
            block.append({"gate": "CRZ", "wires": [i, j], "param": "b"})
            block.append({"gate": "CRZ", "wires": [j, i], "param": "b"})
        elif arm == "control":  # two same-direction CRZs == CRZ at 2b (family-equiv to original)
            block.append({"gate": "CRZ", "wires": [i, j], "param": "b"})
            block.append({"gate": "CRZ", "wires": [i, j], "param": "b"})
        else:
            raise ValueError(arm)
    block += [{"gate": "RY", "wire": i, "param": "c"} for i in range(n)]
    return block


def make_candidate(arm, n, repeats=1, layers=1):
    return {"id": "rep_%s" % arm, "n_qubits": n, "block": arm_block(arm, n),
            "repeats": repeats, "layers": layers,
            "param_names": ["a", "b", "c"], "hypothesis": None,
            "notes": "WP-REPAIR %s arm" % arm,
            "source": {"arm": arm, "model": None, "parent": None}}


def block_channel_residual(arm, n, theta, closure):
    """Mean channel residual of the arm's block operator over the full group."""
    cand = make_candidate(arm, n)
    gates = cand["block"] * cand["repeats"]
    pdict = _cand.param_dict(cand, theta)
    u = _sym.unitary(gates, pdict, n)
    d = _sym.defects(u, closure)
    return {"channel_mean": d["channel_mean"], "channel_max": d["channel_max"],
            "unitary_mean": d["unitary_mean"]}


# --------------------------------------------------------------- teacher/targets
def _sym_readout(task, n):
    """D6-invariant readout: equal weight on every Z_i, zero on Z_iZ_j."""
    w = np.zeros(len(task.observables))
    z_idx = [k for k, o in enumerate(task.observables) if len(o) == 1]
    for k in z_idx:
        w[k] = 1.0 / len(z_idx)
    return w


def _asym_readout(task, n):
    """Site-0 readout (breaks D6) so the teacher signal has a genuine
    symmetry-breaking component."""
    w = np.zeros(len(task.observables))
    w[0] = 1.0  # observables[0] is {Z_0}
    return w


def _predict_readout(cand, task, x, theta, w):
    E = _train.batched_expectations(cand, task, x, theta)
    return E @ w


def teacher_predictions(cand, task, x, closure):
    """Scalar signal f(x) = <Z_0> after the frozen teacher circuit (D6-breaking)."""
    w = _asym_readout(task, int(cand["n_qubits"]))
    return _predict_readout(cand, task, x, cand["_theta"], w)


def _base_function(x, M, c):
    """Frozen random quadratic+linear function of the input vector (a 'teacher'
    that is NOT any compared ansatz family, avoiding the pilot's confound)."""
    x = np.asarray(x, float)
    return np.einsum("ij,jk,ik->i", x, M, x) + x @ c


def _group_average(x, closure, func):
    """Exact Reynolds projection of ``func`` over the group, computed by applying
    every group element to each input row (independent of dataset orbit labels,
    which may be singletons)."""
    acc = np.zeros(len(x))
    for perm in closure:
        acc += func(transform_rows(x, perm))
    return acc / len(closure)


def build_targets(task, teacher_seed, etas):
    """Confound-free targets ``y_eta = h + eta*b`` on the ring benchmark.

    ``h`` is the dataset's ground-truth D6-invariant oracle ``alpha_0`` (NOT any
    compared ansatz family). Each ``teacher_seed`` freezes a random direction
    ``v``; the breaking component ``b`` is the group-centred remainder of ``v.x``
    (centred by the EXACT group average over the D6 closure, not dataset orbit
    labels) normalised to ``mean b^2 = 1`` on train. The analytic invariant-risk
    floor is ``eta^2 * E[b^2]`` (no invariant predictor can beat it).
    """
    x = np.asarray(task.x, float)
    train_mask = np.asarray(task.splits["train"], bool)
    dev_mask = np.asarray(task.splits["validation"], bool)
    closure = group_closure(task.generators)
    h = np.asarray(task.targets["alpha_0"], float)  # ground-truth invariant
    rng = np.random.default_rng(teacher_seed)
    v = rng.normal(size=x.shape[1])
    gbar = _group_average(x, closure, lambda z: z @ v)
    b_raw = (x @ v) - gbar
    scale = float(np.sqrt(np.mean(b_raw[train_mask] ** 2))) or 1.0
    b = b_raw / scale

    def h_func(z):
        z = np.asarray(z, float)
        return np.mean(z * np.roll(z, 1, axis=1), axis=1)  # == alpha_0 oracle

    def b_func(z):
        z = np.asarray(z, float)
        return ((z @ v) - _group_average(z, closure, lambda w: w @ v)) / scale

    out = {}
    for eta in etas:
        y = h + eta * b
        floor_analytic = (eta ** 2) * float(np.mean(b[dev_mask] ** 2))
        xdev = task.x[dev_mask]
        y_func = lambda z, e=eta: h_func(z) + e * b_func(z)
        ybar_dev = _group_average(xdev, closure, y_func)
        floor_empirical = float(np.mean((y_func(xdev) - ybar_dev) ** 2))
        out[eta] = {"y_train": y[train_mask], "y_dev": y[dev_mask],
                    "x_train": x[train_mask], "x_dev": xdev,
                    "floor_analytic": floor_analytic,
                    "floor_empirical": floor_empirical}
    return out, {"closure_order": len(closure),
                 "closure": [list(p) for p in closure],
                 "teacher": "ground-truth invariant alpha_0 + frozen breaking direction v"}


# ------------------------------------------------------------------- experiment
def fit_block(arm, task, x, y, seed, steps, max_train=None, lr=0.05):
    """Train ONLY the 3 block parameters (a,b,c) with a FIXED symmetric readout.

    A fixed D6-invariant readout is what makes an equivariant block yield an
    invariant predictor; a learned readout would erase the inductive bias. Adam
    on MSE, common random numbers (same seed -> identical init across arms).
    """
    from research.core import simulator as _sim
    n = int(task.n_qubits)
    cand = make_candidate(arm, n)
    obs = _train.obs_matrix(task.observables, n)
    w = _sym_readout(task, n)
    x = np.asarray(x); y = np.asarray(y, float).reshape(-1)
    rng = np.random.default_rng(int(seed))
    if max_train and 0 < int(max_train) < len(x):
        keep = np.sort(rng.choice(len(x), size=int(max_train), replace=False))
        x, y = x[keep], y[keep]
    m = len(x)
    theta = rng.uniform(-np.pi, np.pi, size=3)
    plans = [_train._compile_plan(cand, task, x[i]) for i in range(m)]
    state0 = _train._zero_state(n)
    m1 = np.zeros(3); m2 = np.zeros(3); b1, b2, eps = 0.9, 0.999, 1e-8
    for step in range(int(steps)):
        idx = rng.choice(m, size=min(32, m), replace=False)
        g = np.zeros(3); pdict = _cand.param_dict(cand, theta)
        for i in idx:
            psi, cache = plans[i].run(theta, state0)
            E = ((np.abs(psi) ** 2) @ obs.T).reshape(-1)
            resid = float(E @ w) - float(y[i])
            coef = (2.0 / len(idx)) * resid
            g += plans[i].grad(theta, cache, psi * ((coef * w) @ obs))
        if not np.all(np.isfinite(g)):
            break
        t = step + 1
        m1 = b1 * m1 + (1 - b1) * g; m2 = b2 * m2 + (1 - b2) * (g * g)
        theta = theta - lr * (m1 / (1 - b1 ** t)) / (np.sqrt(m2 / (1 - b2 ** t)) + eps)
    dev_pred = _predict_readout(cand, task, x, theta, w)
    train_risk = float(np.mean((dev_pred - y) ** 2))
    return theta, train_risk


def block_dev_risk(arm, task, x, y, theta):
    n = int(task.n_qubits)
    cand = make_candidate(arm, n)
    pred = _predict_readout(cand, task, x, theta, _sym_readout(task, n))
    return float(np.mean((pred - np.asarray(y, float).reshape(-1)) ** 2))


def _metadata():
    meta = {"python": platform.python_version(), "numpy": np.__version__,
            "host": socket.gethostname(), "platform": platform.platform()}
    try:
        import scipy
        meta["scipy"] = scipy.__version__
    except Exception:
        meta["scipy"] = None
    try:
        meta["git_commit"] = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=str(REPO), capture_output=True,
            text=True, timeout=10).stdout.strip() or "unknown"
    except Exception:
        meta["git_commit"] = "unknown"
    return meta


def run(family="ring_n6", etas=(0.0, 0.5, 1.0), arms=ARMS,
        teacher_seeds=(101, 202, 303), opt_seeds=range(8),
        budgets=(200, 400), max_train=256, out=None, verbose=True):
    task = _tasks.load_family(family, development=True, locked=False)
    n = int(task.n_qubits)
    closure = group_closure(task.generators)
    rows = []
    for tseed in teacher_seeds:
        targets, tinfo = build_targets(task, tseed, etas)
        for eta in etas:
            tg = targets[eta]
            for steps in budgets:
                for oseed in opt_seeds:
                    for arm in arms:
                        theta, train_risk = fit_block(
                            arm, task, tg["x_train"], tg["y_train"], int(oseed),
                            int(steps), max_train=max_train)
                        dev = block_dev_risk(arm, task, tg["x_dev"], tg["y_dev"], theta)
                        resid = block_channel_residual(arm, n, theta, closure)
                        rows.append({"family": family, "teacher_seed": int(tseed),
                                     "eta": float(eta), "steps": int(steps),
                                     "opt_seed": int(oseed), "arm": arm,
                                     "dev_risk": dev, "train_loss": train_risk,
                                     "floor_analytic": tg["floor_analytic"],
                                     "floor_empirical": tg["floor_empirical"],
                                     "channel_mean": resid["channel_mean"],
                                     "channel_max": resid["channel_max"],
                                     "theta": theta.tolist()})
                        if verbose:
                            print("t%d eta%.1f steps%d seed%d %-8s dev=%.5f "
                                  "floor=%.5f chanres=%.2e"
                                  % (tseed, eta, steps, oseed, arm, dev,
                                     tg["floor_analytic"], resid["channel_mean"]),
                                  flush=True)
    result = {"scope": "development only; locked holdout never read",
              "family": family, "etas": list(etas), "arms": list(arms),
              "teacher_seeds": list(teacher_seeds),
              "opt_seeds": list(map(int, opt_seeds)), "budgets": list(budgets),
              "max_train": max_train, "group_order": len(closure),
              "rows": rows, "contrasts": analyze(rows), "metadata": _metadata(),
              "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat()}
    if out:
        os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
        with open(out, "w") as fh:
            json.dump(result, fh, indent=1, default=str)
    return result


def paired_contrasts(rows, a, b, eta, steps):
    """Paired (teacher, opt_seed) dev-risk differences a - b at fixed eta,steps."""
    idx = {(r["teacher_seed"], r["opt_seed"]): r["dev_risk"]
           for r in rows if r["arm"] == a and r["eta"] == eta and r["steps"] == steps}
    idxb = {(r["teacher_seed"], r["opt_seed"]): r["dev_risk"]
            for r in rows if r["arm"] == b and r["eta"] == eta and r["steps"] == steps}
    keys = sorted(set(idx) & set(idxb))
    diffs = [idx[k] - idxb[k] for k in keys]  # positive => a worse than b
    return {"a": a, "b": b, "eta": eta, "steps": steps, "n_pairs": len(diffs),
            "mean_diff_a_minus_b": float(np.mean(diffs)) if diffs else None,
            "frac_a_better": float(np.mean([d < 0 for d in diffs])) if diffs else None,
            "diffs": diffs}


def bootstrap_ci(diffs, n_boot=10000, seed=0):
    if not diffs:
        return None
    rng = np.random.default_rng(seed)
    d = np.asarray(diffs)
    means = [float(np.mean(rng.choice(d, size=len(d), replace=True)))
             for _ in range(n_boot)]
    return {"mean": float(np.mean(d)),
            "ci95_low": float(np.percentile(means, 2.5)),
            "ci95_high": float(np.percentile(means, 97.5))}


def analyze(rows):
    out = []
    for eta in sorted({r["eta"] for r in rows}):
        for steps in sorted({r["steps"] for r in rows}):
            for a, b in [("repaired", "control"), ("repaired", "original"),
                         ("control", "original")]:
                c = paired_contrasts(rows, a, b, eta, steps)
                c["bootstrap"] = bootstrap_ci(c["diffs"])
                c["interpretation"] = ("a_worse" if (c["mean_diff_a_minus_b"] or 0) > 0
                                       else "a_better")
                out.append(c)
    return out


def main(argv=None):
    p = argparse.ArgumentParser(prog="research/experiments/repair/repair_experiment.py")
    p.add_argument("--family", default="ring_n6")
    p.add_argument("--etas", default="0,0.5,1")
    p.add_argument("--teacher-seeds", default="101,202,303")
    p.add_argument("--n-opt-seeds", type=int, default=8)
    p.add_argument("--budgets", default="200,400")
    p.add_argument("--max-train", type=int, default=256)
    p.add_argument("--out", default="research/experiments/repair/repair_results.json")
    args = p.parse_args(argv)
    res = run(family=args.family,
              etas=tuple(float(e) for e in args.etas.split(",")),
              arms=ARMS,
              teacher_seeds=tuple(int(s) for s in args.teacher_seeds.split(",")),
              opt_seeds=range(args.n_opt_seeds),
              budgets=tuple(int(b) for b in args.budgets.split(",")),
              max_train=args.max_train, out=args.out)
    print("\n=== CONTRASTS (mean_diff = a - b dev risk; negative => a better) ===")
    for c in res["contrasts"]:
        bs = c["bootstrap"] or {}
        print("eta%.1f steps%-4d %-8s vs %-8s n=%d mean=%+.5f ci=[%+.5f,%+.5f] "
              "frac_a_better=%.2f"
              % (c["eta"], c["steps"], c["a"], c["b"], c["n_pairs"],
                 c["mean_diff_a_minus_b"] or 0, bs.get("ci95_low", 0),
                 bs.get("ci95_high", 0), c["frac_a_better"] or 0))
    return 0


if __name__ == "__main__":
    sys.exit(main())
