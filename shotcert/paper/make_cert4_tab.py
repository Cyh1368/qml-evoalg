"""A4.1/A4.4 matched-certification table + headline sentences, from results/cert4.json.

Menus are size-matched (seven candidates, multiplicity six) and shot-matched, so the logarithm the
simultaneous rules pay for is the same on both sides -- the confound the previous review identified.
"""
import collections
import json

d = json.load(open("shotcert/results/cert4.json"))
agg = collections.defaultdict(lambda: collections.defaultdict(float))
cnt = collections.Counter()
for r in d["rows"]:
    for s, v in r["selectors"].items():
        k = (r["task"], r["menu"], s)
        cnt[k] += 1
        agg[k]["sel"] += v["selection_rate"]
        agg[k]["near"] += v["near_optimal_rate"]
        agg[k]["fail"] += v["failure_rate"]

sels = ["plugin", "student", "mp", "split"]
label = {"plugin": "plug-in", "student": "studentised", "mp": "Maurer-Pontil", "split": "split-sample"}
ncol = 2 + 3 * len(sels)

L = ["% Generated by shotcert/paper/make_cert4_tab.py from results/cert4.json. Do not edit.",
     "\\begin{tabular}{ll" + "ccc" * len(sels) + "}",
     "\\toprule",
     " & & " + " & ".join("\\multicolumn{3}{c}{" + label[s] + "}" for s in sels) + " \\\\",
     "Task & Menu & " + " & ".join(["sel. & near & fail"] * len(sels)) + " \\\\",
     "\\cmidrule(lr){3-5} \\cmidrule(lr){6-8} \\cmidrule(lr){9-11} \\cmidrule(lr){12-14}",
     "\\midrule"]

df_max = (0.0, None)          # highest selection rate achieved by either distribution-free rule
worst_fail = (0.0, None)
for t in sorted({k[0] for k in agg}):
    for mn in sorted({k[1] for k in agg if k[0] == t}):
        cells = []
        for s in sels:
            k = (t, mn, s)
            if k not in agg:
                cells += ["--", "--", "--"]
                continue
            c = cnt[k]
            sel_rate = agg[k]["sel"] / c
            cells += ["%.2f" % sel_rate,
                      "%.2f" % (agg[k]["near"] / c),
                      "%.3f" % (agg[k]["fail"] / c)]
            if s in ("mp", "split") and (df_max[1] is None or sel_rate > df_max[0]):
                df_max = (sel_rate, (t, mn, s))
            if agg[k]["fail"] / c > worst_fail[0]:
                worst_fail = (agg[k]["fail"] / c, k)
        L.append("%s & %s & %s \\\\"
                 % (t.replace("_", "\\textunderscore{}"), mn, " & ".join(cells)))
L.append("\\bottomrule\\end{tabular}")

open("shotcert/paper/tabs_cert4.tex", "w").write("\n".join(L) + "\n")
with open("shotcert/paper/claims_cert4.tex", "w") as f:
    f.write("% Generated by shotcert/paper/make_cert4_tab.py. Do not edit by hand.\n")
    f.write("Over " + str(len(d["rows"])) + " cells and " + str(d["reps"]) + " repetitions each, with "
            "menu size, multiplicity and calibration shots matched across arms, the highest selection "
            "rate either distribution-free rule reaches in any cell is " + "%.4f" % df_max[0]
            + " (\\texttt{" + df_max[1][0].replace("_", "\\_") + "}, " + df_max[1][1]
            + " menu, " + label[df_max[1][2]] + " rule).\n\n")
    f.write("The unguaranteed plug-in rule does act, and it is not free: its worst measured rate of "
            "selecting a policy worse than the baseline by more than $\\varepsilon$ is "
            + "%.3f" % worst_fail[0] + " on \\texttt{" + worst_fail[1][0].replace("_", "\\_")
            + "} with a " + worst_fail[1][1] + " menu.\n\n")
    f.write("Certification is therefore neither worthless nor affordable at these budgets: a rule with "
            "a distribution-free guarantee acts in at most " + "%.2f" % (100.0 * df_max[0])
            + "\\% of repetitions at the best cell, while the rule that acts routinely breaks its own "
            "non-degradation target at up to the rate above. The dilemma is reported rather than "
            "resolved by declaring the guaranteed rule unnecessary.\n")
print("wrote tabs_cert4.tex, claims_cert4.tex; columns:", ncol,
      "max distribution-free selection:", df_max, "worst plug-in failure:", worst_fail)
