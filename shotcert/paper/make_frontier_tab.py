"""A6.3 equal-total-budget frontier table + headline sentences, generated from results/frontier.json."""
import json
d = json.load(open("shotcert/results/frontier.json"))
rows = d["rows"]
# one best row per (task, arm, B)
best = {}
for r in rows:
    k = (r["task"], r["arm"], r["B"])
    if k not in best or r["realised_risk"] < best[k]["realised_risk"]:
        best[k] = r
tasks = sorted({t for t, _, _ in best})
budgets = sorted({b for _, _, b in best})
L = ["% Generated by shotcert/paper/make_frontier_tab.py from results/frontier.json. Do not edit.",
     "\\begin{table}[h]\\centering\\small", "\\begin{tabular}{ll" + "rrr" * len(budgets) + "}",
     "\\toprule", "Task & Arm & " + " & ".join(
         ["$B=%d$: risk & use. & f.b." % b for b in budgets]) + " \\\\", "\\midrule"]
wins = {"sym": 0, "free": 0}
for t in tasks:
    cells = {b: {a: best.get((t, a, b)) for a in ("sym", "free")} for b in budgets}
    line = [t.replace("_", "\\textunderscore{}"), "group"]
    for b in budgets:
        r = cells[b]["sym"]
        line += ["$%.5f$" % r["realised_risk"], "%.2f" % r["useful"], "%.2f" % r["fallback"]] if r \
            else ["--", "--", "--"]
    L.append(" & ".join(line) + " \\\\")
    line = ["", "group-free"]
    for b in budgets:
        r = cells[b]["free"]
        line += ["$%.5f$" % r["realised_risk"], "%.2f" % r["useful"], "%.2f" % r["fallback"]] if r \
            else ["--", "--", "--"]
    L.append(" & ".join(line) + " \\\\")
    for b in budgets:
        s_, f_ = cells[b]["sym"], cells[b]["free"]
        if s_ and f_:
            wins["sym" if s_["realised_risk"] < f_["realised_risk"] else "free"] += 1
    L.append("\\addlinespace")
L += ["\\bottomrule\\end{tabular}",
      "\\caption{A6.3: best realised absolute deployed risk at a fixed total budget $B$, with the "
      "probability of useful selection and of falling back to the baseline. Each arm optimises $n$, $S$ "
      "and its policy under the same $B$; both menus hold seven candidates at the same total $S$, and "
      "shrinkage is available to both arms. Lower is better.}", "\\label{tab:frontier2}", "\\end{table}"]
open("shotcert/paper/tabs_frontier2.tex", "w").write("\n".join(L) + "\n")
n_cell = wins["sym"] + wins["free"]
with open("shotcert/paper/claims_frontier.tex", "w") as f:
    f.write("% Generated. Do not edit by hand.\n")
    f.write("At equal total budget the group arm attains lower realised risk in " + str(wins["sym"])
            + " of " + str(n_cell) + " (task, budget) cells and the group-free arm in "
            + str(wins["free"]) + ". Violation probability is $0.000$ in every cell for both arms.\n\n")
    if wins["sym"] and wins["free"]:
        f.write("Neither arm dominates, so neither a blanket advantage claim nor a blanket dominance "
                "claim is supported by this comparison.\n")
    else:
        f.write("One arm dominates in every cell tested; the claim is scoped to these tasks and "
                "budgets.\n")
print("wrote frontier table; wins:", wins, "of", n_cell)
