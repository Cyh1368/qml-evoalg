"""Emit the manuscript's quantitative claims AS SENTENCES and AS A TABLE from results/matched.json.

A3.1's real lesson. A checker that verifies each number appears somewhere cannot catch a number paired
with the wrong quantity: "power 1.000 at 20,800 shots" quoted a power that exists in the data and a
budget that exists in the data, at points that do not belong together. The structural fix is to stop
typing sentences: everything here is substituted from the result file, so a mispairing would require the
generator to be wrong -- one bug to find instead of many.

Arms are compared at a COMMON shots-per-circuit. Pooling min(best_true_delta) over the whole sweep
compares unequal deployments: on heisenberg_even it reports -0.00206 (the s=64 row) when at matched s=8
the group-free gain is -0.04795. That is the same class of error as the above, caught here before it
reached the text.
"""
from __future__ import annotations

import argparse
import json
import os

S_COMMON = 8
POWER = 0.9


def best_cost(rows, rule, thresh=POWER):
    ok = [r for r in rows if r["selectors"][rule]["power"] >= thresh]
    if not ok:
        return None, None
    r = min(ok, key=lambda x: x["ledger"]["total_shots"])
    return r["ledger"]["total_shots"], r["selectors"][rule]["power"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--res", default="shotcert/results")
    ap.add_argument("--out", default="shotcert/paper")
    a = ap.parse_args()
    path = os.path.join(a.res, "matched.json")
    if not os.path.exists(path):
        print("no matched.json; skipping")
        return
    m = json.load(open(path))
    rows = m["rows"]
    tasks = sorted(set(r["task"] for r in rows))

    def arm(t, name):
        return [r for r in rows if r["task"] == t and r["arm"] == name]

    def best_at(t, name, s_=S_COMMON):
        r = [x for x in arm(t, name) if x["s"] == s_]
        return r[0]["best_true_delta"] if r else float("nan")

    verdicts = {}
    for t in tasks:
        sc, _ = best_cost(arm(t, "sym"), "plugin")
        gc, _ = best_cost(arm(t, "generic"), "plugin")
        v = ("group-free cheaper" if (gc and sc and gc < sc) else
             "group cheaper" if (gc and sc and sc < gc) else
             "neither reaches" if (sc is None and gc is None) else "tied")
        verdicts[t] = {"sym_cost": sc, "generic_cost": gc, "verdict": v}

    L = ["% Generated by shotcert/paper/make_claims.py from results/matched.json. Do not edit by hand.",
         "\\begin{table}[h]\\centering\\small",
         "\\begin{tabular}{lrrrrrl}", "\\toprule",
         "Task & $\\Delta_{\\mathrm{best}}$(grp) & $\\Delta_{\\mathrm{best}}$(grp-free) & $\\epsilon$ "
         "& grp cost & grp-free cost & verdict \\\\", "\\midrule"]
    for t in tasks:
        eps = arm(t, "sym")[0]["eps"]
        L.append("%s & $%+.5f$ & $%+.5f$ & $%.5f$ & %s & %s & %s \\\\"
                 % (t.replace("_", "\\textunderscore{}"), best_at(t, "sym"), best_at(t, "generic"),
                    eps,
                    ("%d" % verdicts[t]["sym_cost"]) if verdicts[t]["sym_cost"] else "none",
                    ("%d" % verdicts[t]["generic_cost"]) if verdicts[t]["generic_cost"] else "none",
                    verdicts[t]["verdict"]))
    caption = (
        "\\caption{A3.4(a) and A3.5: matched-total-resource comparison with shared measurement records "
        "(one record per distinct circuit per instance; every deterministic policy evaluated from it at "
        "zero additional shot cost). $\\Delta_{\\mathrm{best}}$ is quoted at a common $s="
        + str(S_COMMON) + "$ shots per circuit, because pooling across unequal deployments makes the "
        "arms incomparable. Costs are total shots including the declared deployment of "
        + str(m["n_deploy"]) + " predictions; the group arm necessarily pays for $|G|$ circuits.}")
    L += ["\\bottomrule\\end{tabular}", caption, "\\label{tab:matched}", "\\end{table}"]
    open(os.path.join(a.out, "tabs_matched.tex"), "w").write("\n".join(L) + "\n")

    phys = [t for t in tasks if not t.startswith("control")]
    n_gf = sum(1 for t in tasks if verdicts[t]["verdict"] == "group-free cheaper")
    # The gate governs whether an ADVANTAGE may be claimed: it requires the group arm to beat the
    # strongest group-free comparator on both physical mechanisms. "group-free cheaper" therefore
    # means the gate FAILS. Getting this boolean backwards would turn the paper's conclusion over.
    advantage = all(verdicts[t]["verdict"] == "group cheaper" for t in phys)
    mp_any = any(best_cost(arm(t, a_), "mp")[0] for t in tasks for a_ in ("sym", "generic"))
    sents = [
        "Under shared measurement records and matched total resources, the group-free arm reaches the "
        "$0.9$ power threshold at lower total cost than the group arm on " + str(n_gf) + " of "
        + str(len(tasks)) + " tasks, including both physical mechanisms.",
        "The frozen A2.7/A3.5 stop gate, which requires the group arm to win on both physical "
        "mechanisms, therefore " + ("passes." if advantage else
        "FAILS, and the scoped negative is the finding."),
        "The valid Maurer-Pontil rule reaches $0.9$ power somewhere in this sweep: "
        + ("yes, at small shots per circuit." if mp_any else "no."),
    ]
    with open(os.path.join(a.out, "claims_matched.tex"), "w") as f:
        f.write("% Generated by make_claims.py. Do not edit by hand.\n")
        for s in sents:
            f.write(s + "\n\n")
    print("wrote tabs_matched.tex, claims_matched.tex; advantage_claimable=%s" % advantage)
    for s in sents:
        print("  ", s)


if __name__ == "__main__":
    main()
