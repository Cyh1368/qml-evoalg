"""Emit the A6.0 supersession sentence from results/defect_a60.json."""
import json
d = json.load(open("shotcert/results/defect_a60.json"))
with open("shotcert/paper/claims_defect.tex", "w") as f:
    f.write("% Generated by shotcert/paper/make_defect_claim.py from results/defect_a60.json.\n")
    f.write("Measured on \\texttt{" + d["task"].replace("_", "\\_") + "} at $s=" + str(d["s"])
            + "$ (so the scored difference used $S=" + str(d["S"]) + "$ shots): the deployed risk "
            "difference is $" + ("+" if d["delta_deployed"] >= 0 else "") + "%.5f$" % d["delta_deployed"]
            + " while the calibration contrast measured $"
            + ("+" if d["delta_calibration"] >= 0 else "") + "%.5f$" % d["delta_calibration"]
            + ". The offset is $" + "%.5f" % d["offset_measured"] + "$ against the predicted "
            "$\\sigma_0^2/(2s)=" + "%.5f" % d["offset_predicted"] + "$, i.e. "
            + "%.1f" % d["ratio_offset_to_effect"] + " times the effect under study.\n")
print("wrote claims_defect.tex")
