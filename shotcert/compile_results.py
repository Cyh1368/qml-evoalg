"""Compile ShotCert result JSONs into RESULTS.md. Every number in the draft comes from here.

Carried over from the previous project, where two-stage numeric checking caught real errors: the
manuscript never quotes a value that was typed by hand, and this script is the only path from a
result file to a sentence.
"""

from __future__ import annotations

import argparse
import json
import os

REG_ORDER = ("help", "hurt", "interior")
REG_LABEL = {"help": "averaging helps", "hurt": "averaging hurts",
             "interior": "interior policy best"}


def f(x, spec="%.5f"):
    if x is None:
        return "n/a"
    return spec % x


def load(path):
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        return json.load(fh)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="shotcert/results")
    ap.add_argument("--out", default="shotcert/RESULTS.md")
    args = ap.parse_args()
    ctl = load(os.path.join(args.dir, "control.json"))
    phy = load(os.path.join(args.dir, "physics.json"))
    var = load(os.path.join(args.dir, "variance.json"))
    L = []
    L.append("# ShotCert results (auto-compiled; do not edit numbers here)\n")
    L.append("Generated by `shotcert/compile_results.py`.\n")

    if ctl:
        L.append("Generated %s, %.1f s wall.\n" % (ctl["created_utc"], ctl["wall_seconds"]))
        L.append("## 1. Risk decomposition on the 2-qubit control\n")
        L.append("`R_S(a) = bias^2 + V_G/k + Sigma/S`, evaluated exactly; the last column is the "
                 "residual of the identity.\n")
        L.append("| regime | policy | R_S | bias^2 | V_G | Sigma | identity residual |")
        L.append("|---|---|---|---|---|---|---|")
        for reg in REG_ORDER:
            for name, r in ctl["q1_decomposition"][reg]["rows"].items():
                L.append("| %s | %s | %s | %s | %s | %s | %.2e |"
                         % (reg, name, f(r["R"]), f(r["bias2"]), f(r["V_G"]), f(r["Sigma"]),
                            abs(r["identity_gap"])))
        L.append("\nMax identity residual over all regimes and policies: **%.2e**.\n"
                 % max(ctl["q1_decomposition"][r]["max_identity_gap"] for r in REG_ORDER))

        L.append("### F1 - at fixed total shots the (k, S/k) split moves only the draw term\n")
        L.append("| k | V_G | Sigma | R_S |")
        L.append("|---|---|---|---|")
        for row in ctl["q1_decomposition"]["hurt"]["F1"]:
            L.append("| %d | %s | %s | %s |" % (row["k"], f(row["V_G"]), f(row["Sigma"]), f(row["R"])))
        L.append("\n### F2 - a per-circuit switching cost creates an interior optimum\n")
        L.append("| regime | c = 0 | c = 0.02 | c = 0.1 | c = 0.5 |")
        L.append("|---|---|---|---|---|")
        for reg in REG_ORDER:
            cells = {row["c"]: row for row in ctl["q1_decomposition"][reg]["F2"]}
            L.append("| %s | %s | %s | %s | %s |"
                     % (reg,
                        "k*=%d (R=%s)" % (cells[0.0]["k_star"], f(cells[0.0]["R_at_kstar"])),
                        "k*=%d" % cells[0.02]["k_star"],
                        "k*=%d" % cells[0.1]["k_star"],
                        "k*=%d (R=%s)" % (cells[0.5]["k_star"], f(cells[0.5]["R_at_kstar"]))))

        L.append("\n## 2. Certificate coverage and power (eps = 0, delta = 0.05)\n")
        L.append("A violation is selecting a policy whose true risk difference against a0 is "
                 "positive. In the *averaging hurts* regime no policy helps, so the correct output "
                 "is fallback at every size, which is what happens.\n")
        L.append("| regime | n | violation | power | fallback | true best (delta) |")
        L.append("|---|---|---|---|---|---|")
        for row in ctl["q2_coverage"]:
            L.append("| %s | %d | %.3f | %.3f | %.3f | %s (%+.5f) |"
                     % (row["regime"], row["n"], row["violation_rate"], row["power"],
                        row["fallback_rate"], row["true_best"], row["true_best_delta"]))

        L.append("\n## 3. Budget frontier at total B = 6400 (n preparations x S shots)\n")
        for reg in REG_ORDER:
            L.append("\n**%s**\n" % REG_LABEL[reg])
            L.append("| n | S | violation | power | fallback | best true policy (delta) |")
            L.append("|---|---|---|---|---|---|")
            for row in ctl["q3_budget_frontier"]:
                if row["regime"] != reg:
                    continue
                L.append("| %d | %d | %.3f | %.3f | %.3f | %s (%+.5f) |"
                         % (row["n"], row["S"], row["violation_rate"], row["power"],
                            row["fallback_rate"], row["best_true"], row["best_true_delta"]))

    if phy:
        L.append("\n## 4. Physical tasks\n")
        L.append("Declared `eps = %s`, allocations %s.\n"
                 % (f(phy["eps_declared"], "%.3f"), phy["allocs"]))
        for tr in phy["tasks"]:
            L.append("\n### %s\n" % tr["label"])
            L.append("`%s`, Var(Y) = %s, max identity residual %.2e, max MC z-score %s.\n"
                     % (tr["note"], f(tr["y_var"], "%.4f"), tr["max_identity_gap"],
                        f(tr.get("max_mc_z"), "%.2f")))
            L.append("| policy | R_64 | bias^2 | V_G | Sigma | shots used |")
            L.append("|---|---|---|---|---|---|")
            for name, r in tr["risk_S64"].items():
                L.append("| %s | %s | %s | %s | %s | %d |"
                         % (name, f(r["R"]), f(r["bias2"]), f(r["V_G"]), f(r["Sigma"]),
                            r["shots_used"]))
            L.append("\n| n | S | violation | power | fallback | best true (delta) |")
            L.append("|---|---|---|---|---|---|")
            for row in tr["frontier"]:
                L.append("| %d | %d | %.3f | %.3f | %.3f | %s (%+.5f) |"
                         % (row["n"], row["S"], row["violation_rate"], row["power"],
                            row["fallback_rate"], row["best_true"], row["best_true_delta"]))

    if var:
        L.append("\n## 5. Is the frontier statistics or inequality?\n")
        L.append("`Var(D) = between-instance + deployed-noise`. The noise part is what shots buy; "
                 "the between-instance part is what only preparations buy.\n")
        L.append("| regime | S | policy | Var(D) | between | noise |")
        L.append("|---|---|---|---|---|---|")
        for reg in REG_ORDER:
            e = var["regimes"][reg]["var_vs_S"]
            for S in ("4", "16", "64", "256"):
                if S not in e:
                    continue
                for nm in ("strat", "k4"):
                    if nm not in e[S]:
                        continue
                    r = e[S][nm]
                    L.append("| %s | %s | %s | %s | %s | %s |"
                             % (reg, S, nm, f(r["var_total"]), f(r["var_between"]), f(r["var_noise"])))
        L.append("\n### Empirical-Bernstein bound split for the best candidate at each allocation\n")
        L.append("| regime | n | S | mean D | sd | variance term | range term | upper bound |")
        L.append("|---|---|---|---|---|---|---|---|")
        for reg in REG_ORDER:
            for key, d in var["regimes"][reg]["eb_split"].items():
                n, S = key.split("_")
                best = min(d, key=lambda k: d[k]["ub"])
                r = d[best]
                L.append("| %s | %s | %s | %s | %s | %s | %s | %s |"
                         % (reg, n, S, f(r["mean"], "%+.5f"), f(r["sd"], "%.4f"),
                            f(r["var_term"]), f(r["range_term"]), f(r["ub"], "%+.5f")))

    with open(args.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote %s (%d lines)" % (args.out, len(L)))


if __name__ == "__main__":
    main()
